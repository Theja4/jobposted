export type OnboardingLocationOption = {
  value: string;
  label: string;
  description: string;
};

function location(label: string, description: string): OnboardingLocationOption {
  return { value: label, label, description };
}

function uniqueOptions(options: OnboardingLocationOption[]) {
  const seen = new Set<string>();
  return options.filter((option) => {
    const key = option.value.toLowerCase();
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

